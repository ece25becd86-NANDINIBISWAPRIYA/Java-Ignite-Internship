package JavaIgniteDay3;

public class ElseIfLadder_Demo {
	public static void main(String[] args) {
		int marks = 80;
		if(marks >= 90)
		{
			System.out.println("A Grade");
		}
		else if(marks >= 75)
		{
			System.out.println("B Grade");
		}
		else
		{
			System.out.println("Fail");
		}
	}

}
